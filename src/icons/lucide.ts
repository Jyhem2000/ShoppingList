  "soap-dispenser-droplet": SoapDispenserDroplet,
  "spray-can": SprayCan,
  tag: Tag,
  sprout: Sprout,
  sunrise: Sunrise,
  toilet: Toilet,
  triangle: Triangle,
  wheat: Wheat,
  wine: Wine,
